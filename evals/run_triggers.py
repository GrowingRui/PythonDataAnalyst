"""Run the trigger tests and write a readable summary.

    python evals/run_triggers.py                  # the whole suite, 3 runs per case
    python evals/run_triggers.py --runs 1         # a cheaper quick check
    python evals/run_triggers.py --case "neg*"    # only some cases (one glob)
    python evals/run_triggers.py --summarize evals/results/<file>.json   # no new runs

It calls ``claude plugin eval`` on this repository (the Claude Code plugin),
using your own Claude login, so every run costs usage. The summary goes to
``evals/results/<date>-triggers.md``: pass rates per group and every miss.

A case passes when the majority of its runs did the right thing (loaded the
skill for ``pos*`` cases, didn't for ``neg*``). The target is at most one
missed case per group. A run of only a few cases (fewer than
``MIN_CASES_FOR_A_MISS`` in a group) must get every one of them right.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

EVALS = Path(__file__).resolve().parent
ROOT = EVALS.parent
RESULTS = EVALS / "results"
SKILL_MD = ROOT / "skills" / "python-data-analyst" / "SKILL.md"
MIN_CASES_FOR_A_MISS = 12   # smaller groups (a --case subset) may miss none
GROUPS = {"pos": "Should trigger", "neg": "Should not trigger"}


def claude_command() -> list[str]:
    exe = shutil.which("claude")
    if exe:
        return [exe]
    npx = shutil.which("npx")
    if npx:
        return [npx, "--yes", "@anthropic-ai/claude-code"]
    sys.exit("Neither `claude` nor `npx` is on PATH: install Claude Code first.")


def run_eval(json_path: Path, runs: int | None, case: str | None, concurrency: int) -> int:
    cmd = claude_command() + [
        "plugin", "eval", str(ROOT),
        "--ablation", "none",      # only "did the skill load?" is graded; a no-plugin arm adds nothing
        "--scaffold",              # copies the example files in; the scripts are generated by make_cases.py
        "--trust-plugin",          # this repository's own plugin and cases
        "--no-publish",
        "--concurrency", str(concurrency),
        "--json", str(json_path),
    ]
    if runs:
        cmd += ["--runs", str(runs)]
    if case:
        cmd += ["--case", case]
    print("Running:", " ".join(cmd[len(claude_command()):]), flush=True)
    return subprocess.run(cmd, cwd=ROOT).returncode


def skill_description() -> str:
    text = SKILL_MD.read_text(encoding="utf-8")
    m = re.search(r"^description:\s*(.+)$", text, re.MULTILINE)
    return m.group(1).strip() if m else "(not found)"


def skill_version() -> str:
    m = re.search(r'^\s*version:\s*"?([^"\n]+)"?', SKILL_MD.read_text(encoding="utf-8"), re.MULTILINE)
    return m.group(1) if m else "?"


def summarize(result: dict) -> tuple[str, bool]:
    """Markdown summary of one `--json` result, and whether the target was met."""
    rows: dict[str, list[dict]] = {g: [] for g in GROUPS}
    for c in result["cases"]:
        group = c["name"][:3]
        if group not in rows:
            continue
        runs = c["arms"].get("with", [])
        passed = sum(1 for r in runs if r.get("passed"))
        errors = [r["error"] for r in runs if r.get("error")]
        rows[group].append({
            "name": c["name"],
            "prompt": c.get("promptMarkdown", ""),
            "passed": passed,
            "runs": len(runs),
            "ok": len(runs) > 0 and passed * 2 > len(runs),
            "errors": errors,
        })

    lines = [
        f"# Trigger test results, {result.get('startedAt', '')[:10]}",
        "",
        f"- Skill version: {skill_version()}",
        f"- Claude Code: {result.get('claudeVersion', '?')}",
        f"- Cost: ${result.get('costUsd', 0):.2f}, duration {result.get('durationSeconds', 0) / 60:.1f} min",
        f"- Description tested: {skill_description()}",
        "",
        "| Group | Cases passed | Runs passed | Target |",
        "|---|---|---|---|",
    ]
    met = True
    for g, label in GROUPS.items():
        cases = rows[g]
        if not cases:      # e.g. --case "pos*": the other group wasn't run
            continue
        ok = sum(c["ok"] for c in cases)
        runs_ok = sum(c["passed"] for c in cases)
        runs_all = sum(c["runs"] for c in cases)
        need = len(cases) - (1 if len(cases) >= MIN_CASES_FOR_A_MISS else 0)
        hit = ok >= need
        met &= hit
        lines.append(f"| {label} | {ok} of {len(cases)} | {runs_ok} of {runs_all} | "
                     f"{'met' if hit else 'missed'} (at least {need} of {len(cases)}) |")

    misses = [c for g in GROUPS for c in rows[g] if c["passed"] < c["runs"] or not c["runs"]]
    lines += ["", "## Misses", ""]
    if not misses:
        lines.append("None: every run did the right thing.")
    for c in misses:
        verdict = "case failed" if not c["ok"] else "case passed on majority"
        lines.append(f"- **{c['name']}** ({c['passed']} of {c['runs']} runs right, {verdict}): {c['prompt']}")
        for e in c["errors"]:
            lines.append(f"  - error: {e}")
    return "\n".join(lines) + "\n", met


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--runs", type=int, help="runs per case (default: 3, from case.yaml)")
    p.add_argument("--case", help="only cases whose name matches this glob, e.g. 'pos*'")
    p.add_argument("-j", "--concurrency", type=int, default=4, help="runs at once (1-8, default 4)")
    p.add_argument("--summarize", type=Path, metavar="JSON", help="summarize an existing result instead of running")
    a = p.parse_args(argv)

    RESULTS.mkdir(exist_ok=True)
    if a.summarize:
        json_path = a.summarize
    else:
        json_path = RESULTS / f"{datetime.now():%Y-%m-%d-%H%M}-triggers.json"
        run_eval(json_path, a.runs, a.case, a.concurrency)
        if not json_path.exists():
            print("claude plugin eval wrote no result; see its output above.", file=sys.stderr)
            return 2

    text, met = summarize(json.loads(json_path.read_text(encoding="utf-8")))
    md_path = json_path.with_suffix(".md")
    md_path.write_text(text, encoding="utf-8")
    print(text)
    print(f"Summary written to {md_path}")
    return 0 if met else 1


if __name__ == "__main__":
    sys.exit(main())
