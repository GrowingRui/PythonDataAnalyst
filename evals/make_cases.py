"""Build the trigger-test cases for `claude plugin eval` from one list.

Each case checks one thing: does this prompt load the python-data-analyst
skill (``pos*`` cases) or not (``neg*`` cases)? Edit the lists below, then run

    python evals/make_cases.py

It rewrites every ``evals/pos*`` and ``evals/neg*`` folder. Don't edit those
folders by hand; ``tests/test_evals.py`` checks they match this file.

A prompt that names one of the example files (``sales.csv``, ``survey.csv``,
``customers.xlsx``) gets that file in its sandbox: ``claude plugin eval`` only
runs a scaffold script from inside the case folder, so the script and the file
are copied there from ``evals/_fixtures/``.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

EVALS = Path(__file__).resolve().parent
FIXTURES = EVALS / "_fixtures"
FIXTURE_FILES = ("sales.csv", "survey.csv", "customers.xlsx")
SKILL = "python-data-analyst"

# (slug, prompt). Requests a user would type, including indirect ones.
SHOULD_TRIGGER = [
    ("plain-question", "What's wrong with the data in sales.csv?"),
    ("explore", "Explore sales.csv and tell me what stands out."),
    ("indirect-trust", "Can I trust the numbers in survey.csv before I put them in my thesis?"),
    ("excel-sheet", "Check customers.xlsx, sheet 2025, for data quality problems."),
    ("outliers", "Which columns in survey.csv have outliers, and should I remove them?"),
    ("profile", "Profile this dataset for me: sales.csv. Missing values, duplicates, types, the lot."),
    ("charts", "Make some charts of the distributions and correlations in sales.csv."),
    ("report", "Write a short data analysis report on survey.csv for my manager."),
    ("german", "Kannst du dir die Datei sales.csv anschauen und mir sagen, ob die Daten sauber sind?"),
    ("crm-export", "I just got this export (customers.xlsx) from our CRM. Before I build a dashboard on it, is anything off?"),
    ("correlation", "Are unit price and quantity related in sales.csv?"),
    ("describe", "Give me descriptive statistics for every column of survey.csv."),
]

# Mostly near misses: data, pandas, charts or CSV files, but not an analysis.
SHOULD_NOT_TRIGGER = [
    ("sql-query", "Write a SQL query that returns the top 5 customers by total order value, from tables orders(customer_id, amount) and customers(id, name)."),
    ("sine-wave", "Plot a sine wave from 0 to 2*pi with matplotlib."),
    ("pandas-error", "I get KeyError: 'date' after df = pd.read_csv('x.csv') and then df['date']. What does that error mean?"),
    ("convert-format", "Convert sales.csv to JSON Lines."),
    ("p-value", "Explain what a p-value is in simple terms."),
    ("flask-endpoint", "Add a /health endpoint to a Flask app. Just show me the code."),
    ("csv-function", "Write a Python function that reads a CSV file and returns how many rows it has."),
    ("list-tuple", "What's the difference between a list and a tuple in Python?"),
    ("rename-column", "Rename the column qty to quantity in sales.csv."),
    ("email-draft", "Draft a short email to my team saying the Q3 sales report will be a week late."),
    ("install-pandas", "How do I install pandas on Windows?"),
    ("db-schema", "Design a database schema for a library with books, members and loans."),
]

# Enough turns to see the first tool calls, not to finish the analysis:
# only whether the skill loads is graded, so short runs keep the cost low.
MAX_TURNS = 3
TIMEOUT_SECONDS = 180
RUNS = 3
ALLOWED_TOOLS = "[Skill, Read, Glob, Grep]"

SETUP_SH = """#!/usr/bin/env bash
# Generated by evals/make_cases.py. Copies this case's example file into the
# sandbox, so the prompt finds it there as a real user's would.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
cp "$here"/files/* .
"""


def case_names() -> list[tuple[str, str, bool]]:
    """(folder name, prompt, should trigger) for every case."""
    cases = [(f"pos{i:02d}-{slug}", p, True) for i, (slug, p) in enumerate(SHOULD_TRIGGER, 1)]
    cases += [(f"neg{i:02d}-{slug}", p, False) for i, (slug, p) in enumerate(SHOULD_NOT_TRIGGER, 1)]
    return cases


def files_for(prompt: str) -> list[str]:
    return [f for f in FIXTURE_FILES if f in prompt]


def case_yaml(name: str, prompt: str, should: bool, has_files: bool) -> str:
    lines = [
        'schema_version: "1.0"',
        f"name: {name}",
        f"description: {'Should' if should else 'Should NOT'} load the {SKILL} skill.",
        f"tags: [{'should-trigger' if should else 'should-not-trigger'}]",
    ]
    if has_files:
        lines += ["context:", "  scaffold_script: setup.sh"]
    lines += [
        "execution:",
        f"  prompt: {json.dumps(prompt, ensure_ascii=False)}",
        f"  max_turns: {MAX_TURNS}",
        f"  timeout_seconds: {TIMEOUT_SECONDS}",
        f"  allowed_tools: {ALLOWED_TOOLS}",
        f"runs: {RUNS}",
        "graders:",
        "  - type: tool_used",
    ]
    if should:
        lines += ["    name: skill-loaded", "    tool: Skill", f"    input_match: {SKILL}",
                  "    min: 1", "    arm: both"]
    else:
        # min 0 + max 0 + arm both is how `claude plugin eval` spells "must not call".
        lines += ["    name: skill-not-loaded", "    tool: Skill", f"    input_match: {SKILL}",
                  "    min: 0", "    max: 0", "    arm: both"]
    return "\n".join(lines) + "\n"


def build() -> list[Path]:
    for old in [*EVALS.glob("pos[0-9]*"), *EVALS.glob("neg[0-9]*")]:
        shutil.rmtree(old)
    made = []
    for name, prompt, should in case_names():
        d = EVALS / name
        d.mkdir()
        needed = files_for(prompt)
        if needed:
            (d / "files").mkdir()
            for f in needed:
                shutil.copyfile(FIXTURES / f, d / "files" / f)
            (d / "setup.sh").write_text(SETUP_SH, encoding="utf-8", newline="\n")
        (d / "case.yaml").write_text(case_yaml(name, prompt, should, bool(needed)),
                                     encoding="utf-8", newline="\n")
        made.append(d)
    return made


if __name__ == "__main__":
    print(f"Wrote {len(build())} cases to {EVALS}")
